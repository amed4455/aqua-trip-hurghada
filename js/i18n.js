var LANG_NAMES = { ar: 'العربية', en: 'English', es: 'Español', ru: 'Русский', de: 'Deutsch', sk: 'Slovenčina', pt: 'Português' };
var LANG_FLAGS = { ar: '🇪🇬', en: '🇬🇧', es: '🇪🇸', ru: '🇷🇺', de: '🇩🇪', sk: '🇸🇰', pt: '🇵🇹' };
var LANG_STORAGE_KEY = 'aquaTripLang';

function detectDefaultLang(){
  try {
    var saved = localStorage.getItem(LANG_STORAGE_KEY);
    if(saved && TRANSLATIONS[saved]) return saved;
  } catch(e){}
  var browserLang = (navigator.language || 'en').slice(0,2).toLowerCase();
  if(TRANSLATIONS[browserLang]) return browserLang;
  return 'en';
}

function applyLanguage(lang){
  var t = TRANSLATIONS[lang] || TRANSLATIONS.en;
  document.documentElement.lang = lang;
  document.documentElement.dir = t.dir;

  document.querySelectorAll('[data-i18n]').forEach(function(el){
    var key = el.getAttribute('data-i18n');
    if(t[key] !== undefined) el.textContent = t[key];
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach(function(el){
    var key = el.getAttribute('data-i18n-placeholder');
    if(t[key] !== undefined) el.setAttribute('placeholder', t[key]);
  });
  document.querySelectorAll('[data-i18n-aria]').forEach(function(el){
    var key = el.getAttribute('data-i18n-aria');
    if(t[key] !== undefined) el.setAttribute('aria-label', t[key]);
  });

  try { localStorage.setItem(LANG_STORAGE_KEY, lang); } catch(e){}
  window.currentLang = lang;
  window.dispatchEvent(new CustomEvent('languagechange', { detail: { lang: lang, t: t } }));
}

function initLangSwitcher(){
  var toggleBtn = document.getElementById('langCurrent');
  var menu = document.getElementById('langMenu');
  var switcher = document.getElementById('langSwitcher');
  if(!toggleBtn || !menu) return;

  Object.keys(TRANSLATIONS).forEach(function(code){
    var item = document.createElement('button');
    item.type = 'button';
    item.className = 'lang-item';
    item.setAttribute('data-lang', code);
    item.innerHTML = '<span class="lang-flag">' + LANG_FLAGS[code] + '</span><span>' + LANG_NAMES[code] + '</span>';
    item.addEventListener('click', function(){
      applyLanguage(code);
      updateLangCurrent(code);
      switcher.classList.remove('open');
    });
    menu.appendChild(item);
  });

  toggleBtn.addEventListener('click', function(e){
    e.stopPropagation();
    switcher.classList.toggle('open');
  });
  document.addEventListener('click', function(){ switcher.classList.remove('open'); });

  function updateLangCurrent(code){
    toggleBtn.querySelector('.lang-flag').textContent = LANG_FLAGS[code];
    toggleBtn.querySelector('.lang-code').textContent = code.toUpperCase();
    menu.querySelectorAll('.lang-item').forEach(function(el){
      el.classList.toggle('active', el.getAttribute('data-lang') === code);
    });
  }

  var initialLang = detectDefaultLang();
  updateLangCurrent(initialLang);
  applyLanguage(initialLang);
}

document.addEventListener('DOMContentLoaded', initLangSwitcher);
